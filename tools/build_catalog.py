"""Rebuild PROMPTS.md (index) and docs/all-prompts.md (copy-paste catalogue)
from the prompt files in .github/prompts. Run after adding or editing a prompt:

    python tools/build_catalog.py

The prompt files are the source of truth. Each one carries its number, category
and kind in an HTML comment under the front matter:

    <!-- 051 | E. JPA, Hibernate and databases | build -->
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPT_DIR = ROOT / ".github" / "prompts"
KIND_LABEL = {
    "ask": "Analyse (read-only)",
    "plan": "Design (no code)",
    "build": "Implement (plan, approve, code)",
    "write": "Write tests/docs",
}


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    fm = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    meta = re.search(r"^<!-- (\d+) \| (.+?) \| (\w+) -->$", text, re.M)
    title = re.search(r"^# (?:\d+ · )?(.+)$", text, re.M)
    if not (fm and meta and title):
        sys.exit(f"{path.name}: missing front matter, meta comment or title")
    desc = re.search(r"^description: '(.*)'$", fm.group(1), re.M)
    hint = re.search(r"^argument-hint: '(.*)'$", fm.group(1), re.M)
    unq = lambda m: m.group(1).replace("''", "'") if m else ""
    return {
        "num": int(meta.group(1)),
        "category": meta.group(2),
        "kind": meta.group(3),
        "title": title.group(1).strip(),
        "slug": path.name.removesuffix(".prompt.md"),
        "desc": unq(desc),
        "hint": unq(hint),
        "body": text[meta.end():].strip(),
        "file": path.name,
    }


def main() -> None:
    prompts = sorted((parse(p) for p in PROMPT_DIR.glob("*.prompt.md")), key=lambda p: p["num"])
    nums = [p["num"] for p in prompts]
    dupes = sorted({n for n in nums if nums.count(n) > 1})
    if dupes:
        sys.exit(f"duplicate prompt numbers: {dupes}")

    categories: dict[str, list[dict]] = {}
    for p in prompts:
        categories.setdefault(p["category"], []).append(p)

    cell = lambda s: s.replace("|", "\\|")
    index = [
        "# Prompt index",
        "",
        f"{len(prompts)} prompts in {len(categories)} categories. Generated by `tools/build_catalog.py`; do not edit by hand.",
        "",
        "Run a prompt in Copilot Chat by typing `/` and its command, followed by the input shown in its hint,",
        "or open the file and copy the text. Kinds: "
        + "; ".join(f"**{k}** = {v}" for k, v in KIND_LABEL.items()) + ".",
        "",
        "| Category | Prompts |",
        "|---|---|",
    ]
    for cat, items in categories.items():
        anchor = re.sub(r"[^a-z0-9 -]", "", cat.lower()).replace(" ", "-")
        index.append(f"| [{cat}](#{anchor}) | {len(items)} |")
    for cat, items in categories.items():
        index += ["", f"## {cat}", "", "| # | Command | Kind | What it does | Input |", "|---|---|---|---|---|"]
        for p in items:
            index.append(
                f"| {p['num']:03d} | [`/{p['slug']}`](.github/prompts/{p['file']}) | {p['kind']} "
                f"| {cell(p['desc'])} | {cell(p['hint'])} |"
            )
    (ROOT / "PROMPTS.md").write_text("\n".join(index) + "\n", encoding="utf-8", newline="\n")

    full = [
        "# All prompts in one file",
        "",
        "For chat windows without slash-command support: copy a block, replace the `[PLACEHOLDERS]`, paste.",
        "Generated by `tools/build_catalog.py`; do not edit by hand.",
    ]
    for cat, items in categories.items():
        full += ["", f"# {cat}"]
        for p in items:
            full += ["", f"## {p['num']:03d} · {p['title']}  (`/{p['slug']}`)", "", "````markdown",
                     re.sub(r"^# .+\n+", "", p["body"], count=1), "````"]
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "all-prompts.md").write_text("\n".join(full) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(prompts)} prompts, {len(categories)} categories -> PROMPTS.md, docs/all-prompts.md")


if __name__ == "__main__":
    main()
